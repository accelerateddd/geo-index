export function getCountryFlagIconByName(countryName: string): string | null {
  const key = (countryName || '').trim().toLowerCase();
  const iso2 = COUNTRY_NAME_TO_ISO2[key];
  return iso2 ? resolveAssetUrl(`/data/flags/world/${iso2}.svg`) : null;
}

export function getQuizFlagIconUrl(quiz: QuizConfig): string | null {
  if (quiz.iconFlagUrl) return resolveAssetUrl(quiz.iconFlagUrl);

  // 1. Check Australian state tag (e.g. AU-NSW, AU-VIC, etc.)
  const ausStateTag = quiz.tags.find((t) => /^AU-(NSW|VIC|QLD|WA|SA|TAS|NT|ACT)$/.test(t));
  if (ausStateTag) {
    const code = ausStateTag.slice(3).toLowerCase();
    return resolveAssetUrl(`/data/flags/aus/${code}.svg`);
  }

  // 2. Check US state tag (e.g. US-CA, US-TX, etc.)
  const usStateTag = quiz.tags.find((t) => /^US-[A-Z]{2}$/.test(t));
  if (usStateTag) {
    const code = usStateTag.slice(3).toLowerCase();
    return resolveAssetUrl(`/data/flags/usa/${code}.svg`);
  }

  // 3. Check Brazil state tag (e.g. BR-SP)
  const brStateTag = quiz.tags.find((t) => /^BR-[A-Z]{2}$/.test(t));
  if (brStateTag) {
    const code = brStateTag.slice(3).toLowerCase();
    return resolveAssetUrl(`/data/flags/bra/${code}.svg`);
  }

  // 4. Check country name
  return getCountryFlagIconByName(quiz.countryOrRegion);
}
